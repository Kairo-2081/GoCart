-- Validate and lock the cart, create the order, decrement inventory, and empty the cart atomically.
CREATE OR REPLACE PROCEDURE process_checkout(
    p_order_id VARCHAR,
    p_tracking_id VARCHAR,
    p_customer_id VARCHAR,
    p_shipping_fee NUMERIC,
    p_shipping_address TEXT,
    p_billing_address TEXT,
    p_additional_info TEXT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_cart_count INTEGER;
    v_subtotal NUMERIC(10, 2);
    v_items_json TEXT;
    v_product_name TEXT;
    v_requested_quantity INTEGER;
    v_available_stock INTEGER;
BEGIN
    IF p_customer_id IS NULL OR p_shipping_fee IS NULL OR p_shipping_fee < 0 THEN
        RAISE EXCEPTION 'Checkout Failed: Customer and a non-negative shipping fee are required.';
    END IF;

    PERFORM pg_advisory_xact_lock(hashtextextended(p_customer_id, 0));

    SELECT COUNT(*) INTO v_cart_count
    FROM cart
    WHERE customer_id = p_customer_id;

    IF v_cart_count = 0 THEN
        RAISE EXCEPTION 'Checkout Failed: The shopping cart is empty.';
    END IF;

    PERFORM c.id
    FROM cart c
    WHERE c.customer_id = p_customer_id
    ORDER BY c.id
    FOR UPDATE;

    PERFORM p.id
    FROM products p
    JOIN cart c ON c.product_id = p.id
    WHERE c.customer_id = p_customer_id
    ORDER BY p.id
    FOR UPDATE OF p;

    SELECT p.name INTO v_product_name
    FROM cart c
    JOIN products p ON p.id = c.product_id
    JOIN sellers s ON s.id = p.seller_id
    WHERE c.customer_id = p_customer_id
      AND (p.product_status <> 'active' OR s.status IN ('suspended', 'rejected'))
    ORDER BY c.id
    LIMIT 1;

    IF FOUND THEN
        RAISE EXCEPTION 'Checkout Failed: Product % is no longer available.', v_product_name;
    END IF;

    SELECT p.name, c.quantity, p.stock
    INTO v_product_name, v_requested_quantity, v_available_stock
    FROM cart c
    JOIN products p ON p.id = c.product_id
    WHERE c.customer_id = p_customer_id
      AND c.quantity > p.stock
    ORDER BY c.id
    LIMIT 1;

    IF FOUND THEN
        RAISE EXCEPTION 'Checkout Failed: Insufficient stock for %. Requested %, available %.',
            v_product_name, v_requested_quantity, v_available_stock;
    END IF;

    SELECT COALESCE(SUM(c.quantity * p.price), 0.00)
    INTO v_subtotal
    FROM cart c
    JOIN products p ON p.id = c.product_id
    WHERE c.customer_id = p_customer_id;

    SELECT COALESCE(json_agg(json_build_object(
        'Product_ID', p.id,
        'Name', p.name,
        'Price', p.price,
        'Quantity', c.quantity,
        'Image', COALESCE(p.image, ''),
        'Seller_ID', p.seller_id
    ) ORDER BY c.id), '[]'::json)::text
    INTO v_items_json
    FROM cart c
    JOIN products p ON p.id = c.product_id
    WHERE c.customer_id = p_customer_id;

    INSERT INTO orders (
        id, tracking_id, customer_id, items_json, subtotal, shipping_fee, status,
        shipping_address_json, billing_address_json, additional_info, order_placed_at
    ) VALUES (
        p_order_id, p_tracking_id, p_customer_id, v_items_json, v_subtotal, p_shipping_fee,
        'placed', p_shipping_address, p_billing_address, COALESCE(p_additional_info, ''), CURRENT_TIMESTAMP
    );

    INSERT INTO order_items (order_id, product_id, seller_id, product_id_snapshot, seller_id_snapshot, product_name, unit_price, quantity, image)
    SELECT p_order_id, p.id, p.seller_id, p.id, p.seller_id, p.name, p.price, c.quantity, p.image
    FROM cart c
    JOIN products p ON p.id = c.product_id
    WHERE c.customer_id = p_customer_id;

    UPDATE products p
    SET stock = p.stock - c.quantity
    FROM cart c
    WHERE c.customer_id = p_customer_id
      AND p.id = c.product_id;

    DELETE FROM cart WHERE customer_id = p_customer_id;
END;
$$;

-- Summarize approved sellers with at least five product reviews.
CREATE OR REPLACE VIEW top_sellers AS
SELECT
    s.id AS seller_id,
    s.name AS seller_name,
    COUNT(DISTINCT p.id) AS total_active_products,
    COUNT(r.id) AS total_lifetime_reviews,
    COALESCE(ROUND(AVG(r.rating), 2), 0.00) AS overall_average_rating
FROM sellers s
JOIN products p ON p.seller_id = s.id
LEFT JOIN reviews r ON r.product_id = p.id
WHERE s.status = 'approved'
  AND p.product_status = 'active'
GROUP BY s.id, s.name
HAVING COUNT(r.id) >= 5;

-- Rank active products by current cart demand.
CREATE OR REPLACE VIEW trending_products AS
SELECT
    p.id AS product_id,
    p.name AS product_name,
    cat.name AS category_name,
    p.price,
    p.stock AS available_stock,
    COUNT(DISTINCT c.customer_id) AS distinct_customers_wanting_this,
    COALESCE(SUM(c.quantity), 0) AS total_units_in_carts
FROM products p
JOIN cart c ON c.product_id = p.id
JOIN categories cat ON cat.id = p.category_id
WHERE p.product_status = 'active'
GROUP BY p.id, p.name, cat.name, p.price, p.stock;

-- Summarize customer spend and order counts for delivered orders.
CREATE OR REPLACE VIEW top_customers AS
SELECT
        c.id AS customer_id,
        c.name AS customer_name,
    u.email,
        COUNT(o.id) AS total_orders,
        COALESCE(SUM(o.subtotal + o.shipping_fee), 0.00) AS total_lifetime_spent
FROM customers c
JOIN orders o ON o.customer_id = c.id
JOIN users u ON u.id = c.id AND u.role = 'customer'
WHERE o.status = 'delivered'
GROUP BY c.id, c.name, u.email;

-- List active, approved-seller products with at least three strong reviews.
CREATE OR REPLACE VIEW top_rated_products AS
SELECT
        p.id AS product_id,
        p.name AS product_name,
        c.name AS category_name,
        s.name AS seller_name,
        p.price,
        ROUND(AVG(r.rating), 1) AS average_rating,
        COUNT(r.id) AS total_reviews
FROM products p
JOIN categories c ON c.id = p.category_id
JOIN sellers s ON s.id = p.seller_id
JOIN reviews r ON r.product_id = p.id
WHERE p.product_status = 'active'
    AND s.status = 'approved'
GROUP BY p.id, p.name, c.name, s.name, p.price
HAVING COUNT(r.id) >= 3
    AND AVG(r.rating) >= 4.0;

-- Aggregate active inventory and pricing metrics by category.
CREATE OR REPLACE VIEW category_performance AS
SELECT
        c.id AS category_id,
        c.name AS category_name,
        COUNT(p.id) AS total_unique_products,
        COALESCE(SUM(p.stock), 0) AS total_units_in_stock,
        COALESCE(ROUND(AVG(p.price), 2), 0.00) AS average_product_price,
        COALESCE(SUM(p.stock * p.price), 0.00) AS total_inventory_value
FROM categories c
LEFT JOIN products p
    ON p.category_id = c.id
 AND p.product_status = 'active'
GROUP BY c.id, c.name;

