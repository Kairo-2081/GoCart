LANGUAGE SQL STABLE
AS $$
    SELECT * FROM users
    WHERE LOWER(username) = LOWER(p_identifier)
       OR LOWER(email) = LOWER(p_identifier)
       OR id = p_id
    LIMIT 1;
$$;

